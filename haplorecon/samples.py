"""Bundled synthetic fixtures.

Every fixture is generated by hand-written code in ``scripts/make_samples.py``
and uses deliberately abstract binary strings.  No real person's genetic data is
involved, and the sequences do not encode any biological locus.
"""
from __future__ import annotations

import os
from dataclasses import dataclass
from typing import List

HERE = os.path.dirname(os.path.abspath(__file__))
EXAMPLES = os.path.join(os.path.dirname(HERE), "examples")


@dataclass(frozen=True)
class Sample:
    name: str
    title: str
    description: str
    expectation: str
    text: str


def _load(filename: str) -> str:
    path = os.path.join(EXAMPLES, filename)
    with open(path, "r", encoding="utf-8") as fh:
        return fh.read()


_SPECS = [
    (
        "two_blocks",
        "two_blocks.txt",
        "Two disconnected blocks",
        "Two coverage blocks separated by a gap. Each block can be globally flipped, and no "
        "fragment links them.",
        "2 components, flip ambiguity reported for each, a coordinate gap, cost 0.",
    ),
    (
        "single_error",
        "single_error.txt",
        "One measurement error",
        "Ten synthetic fragments from two haplotypes; one call was deliberately flipped.",
        "Cost 1, with the modified fragment's exact error position listed.",
    ),
    (
        "lock_conflict",
        "lock_conflict.txt",
        "Lock that contradicts a fragment",
        "Pinning position 0 to hap0=0 contradicts fragment x1, which matches the other "
        "haplotype there.",
        "The lock raises the cost and x1 appears in the lock conflict list.",
    ),
    (
        "merge_demo",
        "merge_demo.txt",
        "Connector merge demonstration",
        "Two self-contained blocks. Add a connector spanning the middle to merge them.",
        "Component count drops from 2 to 1 and exactly the touched components are re-solved.",
    ),
    (
        "long_scaffold",
        "long_scaffold.txt",
        "Longer scaffold for bounds and timeouts",
        "90 fragments over 300 positions with 4% read errors, large enough that the exact "
        "engine may exceed its state cap.",
        "Either an exact optimum, or status=timeout with a proven lower bound below the cost.",
    ),
]


def _build() -> List[Sample]:
    out = []
    for name, filename, title, description, expectation in _SPECS:
        try:
            text = _load(filename)
        except OSError:
            continue
        out.append(Sample(name, title, description, expectation, text))
    return out


SAMPLES: List[Sample] = _build()
